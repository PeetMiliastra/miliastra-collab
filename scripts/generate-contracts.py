"""Generate the renderer command contract from Tauri command signatures; --check is CI-safe."""

import argparse, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALIASES = {
    "runtime::Snapshot": "Snapshot",
    "assets::Inspection": "SliceInspection",
    "slice_tools::RevertPreview": "RevertPreview",
    "slice_tools::MoveId": "MoveId",
    "miliastra_core::binary::Stage": "Stage",
    "Draft": "Draft",
    "Settings": "Settings",
    "miliastra_core::Update": "Update",
    "miliastra_core::Invitation": "Invitation",
    "conflicts::Preview": "ConflictPreview",
    "installer::Plan": "InstallPlan",
    "miliastra_core::HistoryPage": "HistoryPage",
    "runtime::Task": "WorkflowTask",
    "names::Draft": "NamesDraft",
    "crate::names::Draft": "NamesDraft",
    "SavedConnection": "{id:string;name:string}",
    "portable::AppUpdate": "{version:string;notes:string;canReplace:boolean}",
    "conflicts::Comparison": "{mine:SliceInspection;theirs:SliceInspection}",
    "tasks::StorageCheck": "{baseStage:boolean}",
    "invitation::Details": "{projectName:string;ownerName:string|null;storageKind:string;privacyKeyRequired:boolean;mappedFolder:string|null}",
    "db::HistoryFilter": "{section?:string|null;before?:number|null}",
    "access::AccessStatus": "{status:string;message:string;ownerOnline:boolean|null}",
}


def parts(text):
    result = []
    depth = 0
    start = 0
    for i, c in enumerate(text):
        if c in "<([{":
            depth += 1
        elif c in ">)]}":
            depth -= 1
        elif c == "," and depth == 0:
            result.append(text[start:i].strip())
            start = i + 1
    if text[start:].strip():
        result.append(text[start:].strip())
    return result


def ts(value):
    value = re.sub("\\s+", "", value)
    if value in ["String", "PathBuf"]:
        return "string"
    if value == "bool":
        return "boolean"
    if value == "()":
        return "void"
    if value in ["u8", "u32", "u64", "i64", "usize"]:
        return "number"
    for prefix in ["Option<", "Vec<", "std::collections::BTreeMap<", "BTreeMap<"]:
        if value.startswith(prefix):
            inner = value[len(prefix) : -1]
            if prefix == "Option<":
                return ts(inner) + " | null"
            if prefix == "Vec<":
                return "Array<" + ts(inner) + ">"
            key, val = parts(inner)
            return "Record<" + ts(key) + "," + ts(val) + ">"
    if value not in ALIASES:
        raise ValueError("Unmapped native type: " + value)
    return ALIASES[value]


def commands():
    source = (ROOT / "src-tauri/src/lib.rs").read_text(encoding="utf8")
    records = []
    for match in re.finditer(
        "#\\[tauri::command\\]\\s*(?:async\\s+)?fn\\s+(\\w+)\\s*\\(", source
    ):
        pos = match.end()
        depth = 1
        end = pos
        while depth:
            if source[end] == "(":
                depth += 1
            if source[end] == ")":
                depth -= 1
            end += 1
        parameters = source[pos : end - 1]
        result_start = source.index("Cmd<", end) + 4
        i = result_start
        depth = 1
        while depth:
            if source[i] == "<":
                depth += 1
            if source[i] == ">":
                depth -= 1
            i += 1
        args = []
        for param in parts(parameters):
            name, value = param.split(":", 1)
            name = name.replace("mut ", "").strip()
            value = value.strip()
            if "tauri::State" in value or value == "tauri::AppHandle":
                continue
            camel = re.sub("_([a-z])", lambda m: m[1].upper(), name)
            args.append(
                camel + ("?" if value.startswith("Option<") else "") + ":" + ts(value)
            )
        test_only = (
            "#[cfg(test_build)]" in source[max(0, match.start() - 80) : match.start()]
        )
        records.append(
            (
                match[1],
                "{" + ";".join(args) + "}",
                ts(source[result_start : i - 1]),
                test_only,
            )
        )
    return records


def outputs():
    everything = commands()
    # Test-only commands (#[cfg(test_build)]) are left out of the frontend types and the main
    # capability; test builds register them at startup.
    tests = [r[0] for r in everything if r[3]]
    records = [r[:3] for r in everything if not r[3]]
    imports = "Snapshot,SliceInspection,RevertPreview,MoveId,Stage,Draft,Settings,Update,Invitation,ConflictPreview,InstallPlan,HistoryPage,WorkflowTask,NamesDraft"
    text = (
        "// Generated by scripts/generate-contracts.py. Edit native signatures, then regenerate.\nimport type {"
        + imports
        + '} from "./types";\nexport type CommandMap = {\n'
    )
    text += (
        "".join(
            (
                f"  {name}: {{args:{args};result:{result}}};\n"
                for name, args, result in records
            )
        )
        + "};\n"
    )
    constants = (ROOT / "crates/core/src/domain.rs").read_text(encoding="utf8")
    for name in [
        "MAX_SUMMARY_UNITS",
        "MAX_DETAILS_UNITS",
        "MAX_NAME_UNITS",
        "MAX_SLICE_NAME_UNITS",
    ]:
        value = re.search("pub const " + name + ": usize = ([0-9_]+);", constants)[
            1
        ].replace("_", "")
        text += f"export const {name} = {value};\n"
    capability = {
        "identifier": "main",
        "description": "Only the main window can invoke project commands.",
        "windows": ["main"],
        "permissions": ["core:default", "core:window:allow-set-theme"]
        + ["allow-" + r[0].replace("_", "-") for r in records],
    }
    return {
        ROOT / "src/commands.generated.ts": text,
        ROOT / "src-tauri/commands.generated.rs": "&"
        + json.dumps([r[0] for r in records], indent=2)
        + "\n",
        ROOT / "src-tauri/commands.test.generated.rs": "&"
        + json.dumps(tests, indent=2)
        + "\n",
        ROOT / "src-tauri/capabilities/main.json": json.dumps(capability, indent=2)
        + "\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf8") != text:
                raise SystemExit(f"Regenerate contracts: {path.name}")
        else:
            path.write_text(text, encoding="utf8")
    print(
        "Native command contracts checked"
        if args.check
        else "Native command contracts generated"
    )
